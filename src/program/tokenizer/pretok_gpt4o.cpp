//   |\p{N}{1,3}| ?[^\s\p{L}\p{N}]+[\r\n/]*|\s*[\r\n]+|\s+(?!\S)|\s+
//
// The general category and whitespace flags come from the table pretok_qwen35 uses; the case flag (Lu/Lt against Ll)
// is the one piece of Unicode data that table does not carry, so it is held here as ranges. Both were generated from
// the `regex` module (see tools/tokenizer/gen_gpt4o_fixture.py). The code points are decoded once with their flags,
// and the pieces come back as byte offsets into the UTF-8 text.
