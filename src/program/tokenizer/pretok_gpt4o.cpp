//
// llama.cpp maps `tokenizer.ggml.pre = inkling2` to its GPT-4o regex, which splits words on case as well as on script:
//
//   [^\r\n\p{L}\p{N}]?[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]*[\p{Ll}\p{Lm}\p{Lo}\p{M}]+(?i:'s|'t|'re|'ve|'m|'ll|'d)?
